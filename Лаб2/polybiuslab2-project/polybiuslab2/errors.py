"""Помилки програми. Усі вони мають зрозуміле повідомлення для користувача."""


class CipherError(Exception):
    """Базовий клас: некоректні дані, а не помилка програмування."""


class KeyValidationError(CipherError):
    """Некоректне ключове слово, цифровий ключ або квадрат."""


class TextValidationError(CipherError):
    """Текст або координатний шифротекст має неприйнятний формат."""


class ModeError(CipherError):
    """Невідомий алгоритм, операція або алфавіт."""


class FileIOError(CipherError):
    """Не вдалося прочитати або записати файл (у тому числі не UTF-8)."""
